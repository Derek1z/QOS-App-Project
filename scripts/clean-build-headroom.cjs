#!/usr/bin/env node
/* Free disk headroom before a distribution build so electron-builder never
 * dies mid-way at the portable-compression stage (the disk-full failure mode
 * seen in production: win-unpacked is regenerated, but the portable SFX needs
 * room to write the final exe alongside it).
 *
 * Runs at the start of every `npm run dist` / `npm run dist:portable`:
 *   1. deletes stale qos-smoke-* scratch dirs (reuses clean-smoke-temp.cjs),
 *   2. deletes release/win-unpacked and stale *.nsis.7z intermediates,
 *   3. deletes old smoke-test DB backups in release/backups,
 *   4. aborts with a clear message if the drive still lacks headroom. */
const { readdirSync, statSync, rmSync, statfsSync } = require('node:fs')
const { join } = require('node:path')
const { cleanSmokeTemp } = require('./clean-smoke-temp.cjs')

const PROJECT_ROOT = join(__dirname, '..')
const RELEASE_DIR = join(PROJECT_ROOT, 'release')
// Never delete a directory touched in the last 10 minutes — a smoke run (or a
// manually launched app) could still be writing to it.
const FRESH_MS = 10 * 60 * 1000

// Peak usage during a portable build is roughly win-unpacked (~500 MB) + the
// nsis.7z intermediate (~100 MB) + the final portable exe (~100 MB) + electron
// builder staging. Warn below 1.5 GB, abort below 1.25 GB.
const MIN_FREE_WARN = 1.5 * 1024 * 1024 * 1024
const MIN_FREE_HARD = 1.25 * 1024 * 1024 * 1024

function human(n) {
  return `${(n / (1024 * 1024 * 1024)).toFixed(2)} GB`
}

function cleanReleaseArtifacts() {
  let removed = 0
  try {
    for (const name of readdirSync(RELEASE_DIR)) {
      const p = join(RELEASE_DIR, name)
      let st
      try {
        st = statSync(p)
      } catch {
        continue
      }
      // win-unpacked is fully regenerated by every build — always safe to drop.
      if (st.isDirectory() && name === 'win-unpacked') {
        rmSync(p, { recursive: true, force: true })
        removed++
        continue
      }
      // Stale intermediate 7z from interrupted builds (a fresh one is produced).
      if (st.isFile() && name.endsWith('.nsis.7z')) {
        rmSync(p, { force: true })
        removed++
      }
    }
  } catch {
    /* release dir missing — nothing to clean */
  }

  // Old smoke-test DB backups ("Smoke Test-<ts>.qosdb") accumulate ~23 MB per
  // run in release/backups; keep only ones from the last 10 minutes.
  try {
    const backupsDir = join(RELEASE_DIR, 'backups')
    const now = Date.now()
    for (const name of readdirSync(backupsDir)) {
      if (!name.endsWith('.qosdb')) continue
      const p = join(backupsDir, name)
      try {
        if (now - statSync(p).mtimeMs >= FRESH_MS) {
          rmSync(p, { force: true })
          removed++
        }
      } catch {
        /* already gone or locked — skip */
      }
    }
  } catch {
    /* no backups dir — nothing to clean */
  }

  if (removed > 0) console.log(`clean-build-headroom: removed ${removed} stale build artifact(s)`)
  return removed
}

function checkHeadroom() {
  let free = null
  try {
    const st = statfsSync(PROJECT_ROOT)
    free = st.bavail * st.bsize
  } catch {
    /* statfs unavailable (old Node / exotic fs) — skip the guard */
    return
  }
  if (free < MIN_FREE_HARD) {
    console.error(
      `clean-build-headroom: ABORT — only ${human(free)} free on this drive; the ` +
        `portable build needs ~1.25 GB of headroom. Delete large files or move ` +
        `archives off the drive, then re-run the build.`
    )
    process.exit(1)
  }
  if (free < MIN_FREE_WARN) {
    console.warn(
      `clean-build-headroom: warning — only ${human(free)} free; the portable build ` +
        `will be tight on space.`
    )
  } else {
    console.log(`clean-build-headroom: ${human(free)} free — headroom OK`)
  }
}

if (require.main === module) {
  cleanSmokeTemp()
  cleanReleaseArtifacts()
  checkHeadroom()
}
module.exports = { cleanReleaseArtifacts, checkHeadroom }
